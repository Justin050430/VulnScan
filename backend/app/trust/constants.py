def effective_permissions(org_role=None, project_role=None):
    """Union of the permissions granted by the given roles."""
    permissions = set()
    if org_role:
        permissions |= ORG_ROLE_PERMISSIONS.get(org_role, frozenset())
    if project_role:
        permissions |= PROJECT_ROLE_PERMISSIONS.get(project_role, frozenset())
    return frozenset(permissions)


